-- kotlin/classpath_script.lua: fwcd/ktlsp kotlin-language-server classpath
-- dispatch script (port of src/kotlin/classpathChannel.ts, pure parts).
--
-- fwcd resolves its classpath as
--     global script (~/.config/kotlin-language-server/classpath)
--       .or(workspace scan: maven -> gradle -> in-tree kls-classpath)
--       .or(backup)
-- where `or` is first-non-empty: a global script that PRINTS anything
-- short-circuits the workspace scan entirely, so the stray build.gradle
-- files inside an AOSP tree are never touched — the "no gradle" guarantee
-- comes for free, no importer switches needed. The script runs with the
-- workspace root as CWD and dispatches on $PWD: known AOSP roots cat their
-- jar list; anything else exec's the nvim family fallback or prints
-- nothing (fwcd then falls back to its normal gradle/maven resolution).
--
-- Family protocol (shared with aosp-nav.nvim):
--  * the nvim plugin renders a DYNAMIC script marked
--    "# aosp-nav.nvim classpath";
--  * this plugin renders the DISPATCH script marked "# aosp-nav managed";
--  * on takeover the nvim script is moved to classpath.nvim.bak and kept
--    as the fallback branch of the dispatch script, so nvim-specific
--    scenarios (make-era trees, sibling checkouts, jar fallback dir) keep
--    working; the nvim plugin recognizes our marker and does not rewrite
--    the file — no ping-pong;
--  * rollback restores classpath.nvim.bak to classpath;
--  * a script with NO family marker is a foreign user script: never
--    touched, the channel stays blocked.

local M = {}

M.SCRIPT_MARKER = "# aosp-nav managed"
M.NVIM_MARKER = "# aosp-nav.nvim classpath"
M.NVIM_BACKUP_NAME = "classpath.nvim.bak"
M.SCRIPT_NAME = "classpath" -- no extension: first candidate fwcd checks
M.OWN_DIR = "aosp-nav" -- subdir for per-root jar lists
M.MAX_ROOTS = 32

---POSIX single-quote quoting: everything inside is literal (spaces, $,
---backticks, glob chars) and an embedded ' becomes '\''.
local function sh_quote(s)
  return "'" .. tostring(s):gsub("'", "'\\''") .. "'"
end
M.sh_quote = sh_quote

---Every global script candidate fwcd could pick up (config dir names x
---platform extensions). Our script path is the very first on Linux.
function M.all_global_script_candidates(config_base)
  local exts = { "", ".sh", ".bash" }
  local names = { "kotlin-language-server", "KotlinLanguageServer" }
  local out = {}
  for _, n in ipairs(names) do
    for _, e in ipairs(exts) do
      out[#out + 1] = config_base .. "/" .. n .. "/classpath" .. e
    end
  end
  return out
end

---Classify an existing script's content: "ours" | "family-nvim" | "user" | "none".
function M.script_state(content)
  if content == nil then
    return "none"
  end
  if content:find(M.SCRIPT_MARKER, 1, true) then
    return "ours"
  end
  if content:find(M.NVIM_MARKER, 1, true) then
    return "family-nvim"
  end
  return "user"
end

---Render the dispatch script. map: { [root] = { hash, match_paths = {...},
---digest } }; paths: { jar_list_path = fn(hash), nvim_backup_path = fn }.
---Ordering: roots are emitted in a deterministic (sorted) order so the
---content compare is stable.
function M.build_script(map, paths)
  local roots = {}
  for r in pairs(map) do
    roots[#roots + 1] = r
  end
  table.sort(roots)

  local manifest = {}
  for _, r in ipairs(roots) do
    local e = map[r]
    manifest[#manifest + 1] = string.format("%s:%s", e.hash, e.digest or "0")
  end

  local lines = {
    "#!/bin/sh",
    M.SCRIPT_MARKER .. " -- regenerated by aosp-nav.nvim; do not edit.",
    "# Dispatches the kotlin-language-server classpath by workspace root.",
    "# Known roots cat their jar list; others fall through to the nvim family",
    "# script (make-era trees, sibling checkouts) or to fwcd's gradle/maven.",
    -- the manifest line changes whenever any jar list changes, so ktlsp's
    -- content-hash classpath cache can never serve a stale list
    "# manifest " .. table.concat(manifest, " "),
  }
  for _, r in ipairs(roots) do
    local e = map[r]
    local txt = paths.jar_list_path(e.hash)
    for _, mp in ipairs(e.match_paths or {}) do
      lines[#lines + 1] =
        string.format('if [ "$PWD" = %s ]; then cat %s; exit 0; fi', sh_quote(mp), sh_quote(txt))
    end
  end
  local bak = paths.nvim_backup_path()
  lines[#lines + 1] = string.format("[ -x %s ] && exec %s", sh_quote(bak), sh_quote(bak))
  lines[#lines + 1] = "exit 0"
  return table.concat(lines, "\n") .. "\n"
end

---Keep the dispatch table bounded: drop the least recently injected roots.
---Mutates map; returns nothing.
function M.trim_map(map, max_roots)
  max_roots = max_roots or M.MAX_ROOTS
  local entries = {}
  for root, e in pairs(map) do
    entries[#entries + 1] = { root = root, last_used = e.last_used or 0 }
  end
  if #entries <= max_roots then
    return
  end
  table.sort(entries, function(a, b)
    return a.last_used < b.last_used
  end)
  local to_drop = #entries - max_roots
  for i = 1, to_drop do
    map[entries[i].root] = nil
  end
end

---Compute the match_paths for one root: the root itself plus any workspace
---folder located inside it (fwcd CWDs).
function M.match_paths_for(root, workspace_folders)
  local paths = { [root] = true }
  for _, f in ipairs(workspace_folders or {}) do
    if f == root or f:sub(1, #root + 1) == root .. "/" then
      paths[f] = true
    end
  end
  local out = {}
  for p in pairs(paths) do
    out[#out + 1] = p
  end
  table.sort(out)
  return out
end

---Pure part of apply: decide the takeover action from the current script
---content. Returns { action = "blocked"|"takeover-nvim"|"ok", state = ... }.
function M.plan_takeover(current_content)
  local state = M.script_state(current_content)
  if state == "user" then
    return { action = "blocked", state = state }
  end
  if state == "family-nvim" then
    return { action = "takeover-nvim", state = state }
  end
  return { action = "ok", state = state }
end

return M
