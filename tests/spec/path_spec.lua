local t = require("t")
local path = require("aosp-nav.util.path")

t.describe("util/path", function()
  t.describe("join", function()
    t.it("joins and normalizes", function()
      t.raw_eq(path.join("a", "b"), "a/b", "join a b")
      t.raw_eq(path.join("/a", "", "b"), "/a/b", "empty segment")
      t.raw_eq(path.join("/a/", "b/"), "/a/b", "trailing slashes")
      t.raw_eq(path.join("/a/b/../c"), "/a/c", ".. resolves")
      t.raw_eq(path.join(".", "x"), "x", "dot base")
    end)
  end)

  t.describe("parent", function()
    t.it("returns the directory above", function()
      t.raw_eq(path.parent("/a/b/c"), "/a/b")
      t.raw_eq(path.parent("/x"), "/")
      t.raw_eq(path.parent("/"), "/")
      t.raw_eq(path.parent("x"), ".")
    end)
  end)

  t.describe("relative", function()
    t.it("relative inside", function()
      t.raw_eq(path.relative("/a", "/a/b/c"), "b/c")
      t.raw_eq(path.relative("/a", "/a"), "")
      t.raw_eq(path.relative("/a/b", "/a"), nil, "outside -> nil")
      t.raw_eq(path.relative("/a", "/b"), nil, "sibling -> nil")
    end)
    t.it("is_within", function()
      t.truthy(path.is_within("/a", "/a/b/c"))
      t.truthy(path.is_within("/a", "/a"))
      t.truthy(path.is_within("/", "/anything"))
      t.falsy(path.is_within("/a", "/ab"))
    end)
  end)

  t.describe("basename/extname", function()
    t.it("splits like Node", function()
      t.raw_eq(path.basename("/a/b/c.txt"), "c.txt")
      t.raw_eq(path.extname("/a/b/c.cpp"), ".cpp")
      t.raw_eq(path.extname("/a/b/noext"), "")
      t.raw_eq(path.extname("/a/b/d."), ".") -- Node: extname("d.") === "."
    end)
  end)

  t.describe("resolve", function()
    t.it("resolves against base or keeps absolute", function()
      t.raw_eq(path.resolve("/aosp", "frameworks/base"), "/aosp/frameworks/base")
      t.raw_eq(path.resolve("/aosp", "/abs/path"), "/abs/path")
    end)
  end)
end)
